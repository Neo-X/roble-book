#!/usr/bin/env bash
# buildbook.sh — Link textbook content from RobotLearningLectures into the website,
# then build the Jekyll site to verify everything compiles.
#
# Chapter sources (text.md, figures/, chapter.pdf) and the shared pandoc inputs
# are relative symlinks into ../RobotLearningLectures, never copies, so nothing
# is duplicated in this repo. Jekyll follows them; _config.yml's `exclude`
# keeps non-image files in figures/ out of _site, and
# _plugins/dereference_symlinks.rb turns any linked file in _site into a real
# copy so the FTP deploy uploads files, not links.
#
# Usage:
#   ./buildbook.sh           # sync all configured lectures and build
#   ./buildbook.sh lec00     # sync only lec00, then build
#   ./buildbook.sh --no-build lec01  # sync only, skip the Jekyll build
#
# Source repo is expected at ../RobotLearningLectures/ relative to this repo.
# Override with: LECTURES_REPO=/path/to/RobotLearningLectures ./buildbook.sh

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LECTURES_REPO="${LECTURES_REPO:-"$REPO_ROOT/../RobotLearningLectures"}"
DOCS="$REPO_ROOT/docs"

# Mapping: short-id → source directory name in RobotLearningLectures
# Add a new entry here when a lecture gains a compiled chapter.
declare -A LECTURE_MAP=(
    ["lec00"]="lec00-WhatIsRobotLearning"
    ["lec01"]="lec01-SupervisedLearning"
)

# link SRC DEST — point DEST at SRC with a relative symlink, replacing a copy
# left at DEST by the old copy-based sync.
link() {
    local src="$1" dest="$2"
    if [[ -e "$dest" && ! -L "$dest" ]]; then rm -rf "$dest"; fi
    mkdir -p "$(dirname "$dest")"
    ln -sfn "$(realpath --relative-to="$(dirname "$dest")" "$src")" "$dest"
}

# ── Parse arguments ───────────────────────────────────────────────────────────
DO_BUILD=true
SELECTED=()

for arg in "$@"; do
    case "$arg" in
        --no-build) DO_BUILD=false ;;
        *) SELECTED+=("$arg") ;;
    esac
done

# If no lectures specified, sync all
if [[ ${#SELECTED[@]} -eq 0 ]]; then
    SELECTED=("${!LECTURE_MAP[@]}")
fi

# ── Validate source repo ──────────────────────────────────────────────────────
if [[ ! -d "$LECTURES_REPO" ]]; then
    echo "ERROR: RobotLearningLectures repo not found at: $LECTURES_REPO"
    echo "Set LECTURES_REPO env var to point to the correct path."
    exit 1
fi

echo "Source repo : $LECTURES_REPO"
echo "Website docs: $DOCS"
echo ""

# ── Link shared pandoc inputs ─────────────────────────────────────────────────
# ChapterGenerator compiles text.md with the same files the LaTeX chapter
# build uses in RobotLearningLectures.
for f in defs.md flatten-layout.lua sample.bib glossary.tex pandoc-svg.py; do
    link "$LECTURES_REPO/$f" "$DOCS/_pandoc/$f"
done
# Overleaf syncs of the source repo drop the executable bit, and pandoc
# needs it to run the filter via its `uv run` shebang.
chmod +x "$LECTURES_REPO/pandoc-svg.py"
echo "✓ _pandoc/ → defs.md, flatten-layout.lua, sample.bib, glossary.tex, pandoc-svg.py"

# ── Export front-matter pages ─────────────────────────────────────────────────
# front-matter/<name>.md (also built into the book) → docs/<name>.md as a
# standalone page. Its YAML header supplies title and permalink; the leading
# <!-- ... --> source note is dropped.
for src in "$LECTURES_REPO"/front-matter/*.md; do
    [[ -f "$src" ]] || continue
    out="$DOCS/$(basename "$src")"
    awk '
        NR == 1 && /^---$/ { yaml = 1; print; print "layout: page"; next }
        yaml && /^---$/    { yaml = 0; print
                             print "<!-- Generated by buildbook.sh from RobotLearningLectures/front-matter/. Edit it there. -->"
                             next }
        yaml               { print; next }
        /^<!--/            { skip = 1 }
        skip               { if (/-->/) skip = 0; next }
        { print }
    ' "$src" > "$out"
    echo "✓ front-matter/$(basename "$src") → docs/$(basename "$src")"
done
echo ""

# ── Sync each lecture ─────────────────────────────────────────────────────────
for lec_id in "${SELECTED[@]}"; do
    src_name="${LECTURE_MAP[$lec_id]:-}"
    if [[ -z "$src_name" ]]; then
        echo "SKIP: '$lec_id' not in LECTURE_MAP (edit buildbook.sh to add it)"
        continue
    fi

    src_dir="$LECTURES_REPO/$src_name"
    if [[ ! -d "$src_dir" ]]; then
        echo "SKIP: source directory not found: $src_dir"
        continue
    fi

    echo "=== $lec_id ($src_name) ==="

    # 1. text.md → docs/_lectures/<src_name>/text.md
    #    The ChapterGenerator plugin picks up every _lectures/*/text.md and
    #    compiles it with pandoc into _includes/chapters/<src_name>-content.html.
    #    The lecture front matter (docs/_lectures/<lec_id>.md) then references
    #    that include via chapter_content_include.
    #    Jekyll never publishes it as a page: _config.yml has a
    #    `published: false` default for each _lectures/<src_name>/ (checked below).
    link "$src_dir/text.md" "$DOCS/_lectures/$src_name/text.md"
    echo "  ✓ _lectures/$src_name/text.md → source"

    # 2. docs/assets/chapters/<src_name>/figures/ → the lecture's figures/.
    #    _config.yml's `exclude` keeps everything but images out of _site.
    if [[ -d "$src_dir/figures" ]]; then
        link "$src_dir/figures" "$DOCS/assets/chapters/$src_name/figures"
        echo "  ✓ assets/chapters/$src_name/figures/ → source"
    fi

    # 2b. Figures borrowed from other lectures (../lecYY-Name/figures/...).
    #     Only that lecture's figures/ folder is linked, not its chapter.
    for dep in $(grep -oE '\.\./[A-Za-z0-9_-]+/figures/' "$src_dir/text.md" | cut -d/ -f2 | sort -u); do
        if [[ "$dep" != "$src_name" && -d "$LECTURES_REPO/$dep/figures" ]]; then
            link "$LECTURES_REPO/$dep/figures" "$DOCS/assets/chapters/$dep/figures"
            echo "  ✓ borrowed figures/ from $dep"
        fi
    done

    # 2c. Warn about things that work in the PDF but not on the web.
    #     LaTeX finds images without an extension; browsers do not.
    grep -nE '\]\([^)]*figures/[^).]+\)' "$src_dir/text.md" \
        | sed 's/^/  ⚠ image without file extension (broken on web), line /' || true
    #     Browsers can't show PDF images, and figure PDFs are excluded from _site.
    grep -nE '\]\([^)]*figures/[^)]+\.pdf\)' "$src_dir/text.md" \
        | sed 's/^/  ⚠ PDF image (broken on web; use the .svg), line /' || true
    #     Raw LaTeX (minipage, \includegraphics, ...) is dropped from the HTML;
    #     it needs a ::: {.html-only} twin (see flatten-layout.lua).
    if grep -q '\\includegraphics' "$src_dir/text.md" && ! grep -q 'html-only' "$src_dir/text.md"; then
        grep -n '\\includegraphics' "$src_dir/text.md" \
            | sed 's/^/  ⚠ raw \\includegraphics with no ::: {.html-only} twin (missing on web), line /'
    fi
    #     Browsers refuse malformed SVG (e.g. a bare "&" in a label) and show the
    #     alt text instead; Inkscape tolerates it, so the PDF looks fine.
    uv run python -I -c '
import sys, xml.dom.minidom as m
for f in sys.argv[1:]:
    try: m.parse(f)
    except Exception as e: print(f"  ⚠ invalid SVG (broken on web): {f.split(\"/figures/\")[-1]}: {e}")
' "$src_dir"/figures/*.svg 2>/dev/null || true
    #     Jekyll must be told not to publish the chapter source directory.
    grep -q "_lectures/$src_name\"" "$DOCS/_config.yml" \
        || echo "  ⚠ add a 'published: false' default for _lectures/$src_name to docs/_config.yml"

    # 3. docs/assets/chapters/<src_name>/chapter.pdf → the built chapter PDF
    #    (gitignored in the source repo; `make chapter` builds it).
    if [[ -f "$src_dir/chapter.pdf" ]]; then
        link "$src_dir/chapter.pdf" "$DOCS/assets/chapters/$src_name/chapter.pdf"
        echo "  ✓ assets/chapters/$src_name/chapter.pdf → source"
    else
        echo "  ⚠ no chapter.pdf yet — run 'make chapter' in $src_name"
    fi

    echo ""
done

# ── Build the site ────────────────────────────────────────────────────────────
if [[ "$DO_BUILD" == true ]]; then
    echo "=== Building Jekyll site ==="
    cd "$DOCS"
    bundle exec jekyll build
    echo ""
    echo "Build succeeded. Site output: docs/_site/"
else
    echo "Skipping build (--no-build). Run 'cd docs && bundle exec jekyll build' to verify."
fi
